export default async function handler(req, res) {
  res.setHeader('Access-Control-Allow-Origin', '*');
  res.setHeader('Access-Control-Allow-Methods', 'POST, OPTIONS');
  res.setHeader('Access-Control-Allow-Headers', 'Content-Type');

  if (req.method === 'OPTIONS') return res.status(200).end();
  if (req.method !== 'POST') return res.status(405).json({ error: 'Method not allowed' });

  try {
    const { theme, urgency, season, extra } = req.body;

    if (!theme) return res.status(400).json({ error: 'テーマを入力してください' });

    const prompt = `あなたはMOEGIのメルマガ専門家です。過去のメルマガデータと商品情報を完全に把握しています。

${MOEGI_BRAND}

${MOEGI_VOICE}

${MOEGI_DATA}

${NEWSLETTER_RULES}

## 今回の依頼
- テーマ：${theme}
- 緊急性・期限：${urgency || '特になし（季節感・限定感で工夫すること）'}
- 季節・時期の背景：${season || '6月下旬・夏前'}
- 追加情報：${extra || 'なし'}

## 出力ルール
3パターンのメルマガを作成する。各パターンは異なるアプローチで書く。
必ず以下の形式で出力すること。

===パターン1件名===
（件名テキストのみ）
===パターン1本文===
（本文700〜1000字。構成を守る）
===パターン1改善ポイント===
（なぜ売れるか3点箇条書き）

===パターン2件名===
（件名テキストのみ）
===パターン2本文===
（本文700〜1000字。パターン1と異なるアプローチ）
===パターン2改善ポイント===
（なぜ売れるか3点箇条書き）

===パターン3件名===
（件名テキストのみ）
===パターン3本文===
（本文700〜1000字。パターン1・2と異なるアプローチ）
===パターン3改善ポイント===
（なぜ売れるか3点箇条書き）`;

    const response = await fetch('https://api.anthropic.com/v1/messages', {
      method: 'POST',
      headers: {
        'x-api-key': process.env.ANTHROPIC_API_KEY,
        'anthropic-version': '2023-06-01',
        'content-type': 'application/json',
      },
      body: JSON.stringify({
        model: 'claude-sonnet-4-6',
        max_tokens: 6000,
        messages: [{ role: 'user', content: prompt }],
      }),
    });

    if (!response.ok) {
      const error = await response.json();
      return res.status(500).json({ error: error.error?.message || 'API error' });
    }

    const data = await response.json();
    return res.status(200).json({ result: data.content[0].text });
  } catch (err) {
    return res.status(500).json({ error: err.message });
  }
}
